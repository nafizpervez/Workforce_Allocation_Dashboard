/* Allocation classification, fiscal-year utilization and revenue metrics. */
const RESOURCE_SUMMARY_COLUMNS = Object.freeze({
  allocation: Object.freeze([
    Object.freeze({ key: 'intrasourcing', label: 'Intrasourcing' }),
    Object.freeze({ key: 'local', label: 'Local' }),
    Object.freeze({ key: 'preSale', label: 'Pre-Sale' }),
    Object.freeze({ key: 'training', label: 'Training' }),
    Object.freeze({ key: 'skillDevelopment', label: 'Skill Development' }),
    Object.freeze({ key: 'generalAdmin', label: 'General Admin' }),
  ]),
  revenue: Object.freeze([
    Object.freeze({ key: 'intrasourcing', label: 'Intrasourcing' }),
    Object.freeze({ key: 'local', label: 'Local' }),
    Object.freeze({ key: 'preSale', label: 'Pre-Sale' }),
    Object.freeze({ key: 'training', label: 'Training' }),
  ]),
});

const RESOURCE_ALLOCATION_RULES = Object.freeze([
  Object.freeze({
    key: 'intrasourcing',
    label: 'Intrasourcing',
    pattern: /intrasource/i,
    description: 'Project name contains “Intrasource”.',
  }),
  Object.freeze({
    key: 'preSale',
    label: 'Pre-Sale',
    pattern: /pre[\s-]*sale/i,
    description: 'Project name contains “Pre-Sale” or “Pre-Sale”.',
  }),
  Object.freeze({
    key: 'training',
    label: 'Training',
    pattern: /training[\s-]*delivery/i,
    description: 'Project name contains “Training Delivery” or “Training-Delivery”.',
  }),
  Object.freeze({
    key: 'skillDevelopment',
    label: 'Skill Development',
    pattern: /skill[\s-]*development/i,
    description: 'Project name contains “Skill Development” or “Skill-Development”.',
  }),
  Object.freeze({
    key: 'generalAdmin',
    label: 'General Admin',
    pattern: /general[\s-]*admin/i,
    description: 'Project name contains “General Admin” or “General-Admin”.',
  }),
]);

const RESOURCE_ALLOCATION_RULE_BY_KEY = Object.freeze(
  Object.fromEntries(RESOURCE_ALLOCATION_RULES.map(rule => [rule.key, rule])),
);

const NOT_LOCAL_ALLOCATION_KEY_PREFIX = 'notLocalProject:';

function getSummaryAssignmentProject(assignment) {
  return S.projects.find(item =>
    Number(item.id) === Number(assignment?.project_id),
  ) || null;
}

function getNotLocalAllocationKey(projectId) {
  return `${NOT_LOCAL_ALLOCATION_KEY_PREFIX}${Number(projectId)}`;
}

function isNotLocalAllocationKey(key) {
  return String(key || '').startsWith(NOT_LOCAL_ALLOCATION_KEY_PREFIX);
}

function getMatrixNotLocalProjects() {
  return (S.projects || [])
    .filter(project => Number(project?.not_local_project) === 1 && Number.isFinite(Number(project?.id)))
    .slice()
    .sort((left, right) => {
      const leftLabel = String(left?.name || left?.code || '').trim();
      const rightLabel = String(right?.name || right?.code || '').trim();
      const byLabel = leftLabel.localeCompare(rightLabel, undefined, { sensitivity: 'base' });
      return byLabel || Number(left.id) - Number(right.id);
    });
}

function getResourceSummaryAllocationColumns() {
  const notLocalColumns = getMatrixNotLocalProjects().map(project => ({
    key: getNotLocalAllocationKey(project.id),
    label: String(project.name || project.code || `Project ${project.id}`).trim(),
    description: `Assignments for the Not Local project “${String(project.name || project.code || project.id).trim()}”.`,
    projectId: Number(project.id),
    projectCode: String(project.code || '').trim(),
    isNotLocalProject: true,
  }));

  return [...RESOURCE_SUMMARY_COLUMNS.allocation, ...notLocalColumns];
}

function getNotLocalProjectIdFromKey(key) {
  if (!isNotLocalAllocationKey(key)) return null;
  const projectId = Number(String(key).slice(NOT_LOCAL_ALLOCATION_KEY_PREFIX.length));
  return Number.isFinite(projectId) ? projectId : null;
}

function getNotLocalProjectRevenueRateKey(project) {
  const baseCategoryKey = classifyAllocationProject(project?.name || project?.code || '');
  return Object.prototype.hasOwnProperty.call(RESOURCE_REVENUE_RATE_FIELDS, baseCategoryKey)
    ? baseCategoryKey
    : 'local';
}

function getResourceSummaryRevenueColumns() {
  const standardColumns = RESOURCE_SUMMARY_COLUMNS.revenue.map(column => ({
    ...column,
    rateKey: column.key,
    isNotLocalProject: false,
  }));
  const notLocalColumns = getMatrixNotLocalProjects().map(project => ({
    key: getNotLocalAllocationKey(project.id),
    label: String(project.name || project.code || `Project ${project.id}`).trim(),
    description: `Revenue generated by assignments for the Not Local project “${String(project.name || project.code || project.id).trim()}”.`,
    projectId: Number(project.id),
    projectCode: String(project.code || '').trim(),
    rateKey: getNotLocalProjectRevenueRateKey(project),
    isNotLocalProject: true,
  }));

  return [...standardColumns, ...notLocalColumns];
}

function getResourceSummaryRevenueColumn(revenueKey) {
  return getResourceSummaryRevenueColumns().find(column => column.key === revenueKey) || null;
}

function getResourceSummaryBreakdownColumns() {
  const revenueKeys = new Set(getResourceSummaryRevenueColumns().map(column => column.key));
  return getResourceSummaryAllocationColumns().map(column => ({
    ...column,
    hasRevenueColumn: revenueKeys.has(column.key),
  }));
}

function getAllocationColumnDescription(column) {
  if (column?.description) return column.description;
  const rule = RESOURCE_ALLOCATION_RULE_BY_KEY[column?.key];
  return rule?.description ||
    'All projects not classified as Intrasourcing, Pre-Sale, Training, Skill Development, General Admin, or a named Not Local project.';
}

function buildMatrixStickyLeftExpression(allocationColumnCount, revenueColumnIndex = null) {
  const allocationTerms = Array.from(
    { length: Math.max(0, Number(allocationColumnCount) || 0) },
    () => 'var(--allocation-w)',
  );
  const revenueTerms = revenueColumnIndex === null
    ? []
    : Array.from(
      { length: Math.max(0, Number(revenueColumnIndex) || 0) },
      () => 'var(--revenue-w)',
    );
  const terms = ['var(--sn-w)', 'var(--name-w)', ...allocationTerms, ...revenueTerms];
  return `calc(${terms.join(' + ')})`;
}

function getMatrixAllocationStickyStyle(index) {
  return `--matrix-sticky-left:${buildMatrixStickyLeftExpression(index)};`;
}

function getMatrixRevenueStickyStyle(index, allocationColumnCount) {
  return `--matrix-sticky-left:${buildMatrixStickyLeftExpression(allocationColumnCount, index)};`;
}

/* Standard revenue columns use the configured Intrasourcing or Local hourly
 * rates. Every Not Local project receives an additional revenue column and
 * uses the rate associated with its underlying project classification. */
const RESOURCE_REVENUE_RATE_FIELDS = Object.freeze({
  intrasourcing: 'intrasourcing_rate',
  local: 'local_rate',
  preSale: 'local_rate',
  training: 'local_rate',
});

function getSummaryAssignmentProjectName(assignment) {
  if (assignment?.project_name) return String(assignment.project_name).trim();
  return String(getSummaryAssignmentProject(assignment)?.name || '').trim();
}

function normalizeAllocationProjectName(value) {
  return String(value || '')
    .replace(/[‐‑‒–—−_]+/g, '-')
    .replace(/\s*-\s*/g, '-')
    .replace(/\s+/g, ' ')
    .trim();
}

function classifyAllocationProject(projectName) {
  const normalizedName = normalizeAllocationProjectName(projectName);
  if (isUnavailableProjectName(normalizedName)) return 'unavailable';

  const matchingRule = RESOURCE_ALLOCATION_RULES.find(rule =>
    rule.pattern.test(normalizedName),
  );

  return matchingRule?.key || 'local';
}

function classifyResourceSummaryAssignment(assignment) {
  const projectName = getSummaryAssignmentProjectName(assignment);
  if (isUnavailableProjectName(normalizeAllocationProjectName(projectName))) {
    return 'unavailable';
  }

  const project = getSummaryAssignmentProject(assignment);
  const isNotLocalProject = Number(
    assignment?.project_not_local_project ?? project?.not_local_project,
  ) === 1;

  if (isNotLocalProject && Number.isFinite(Number(assignment?.project_id ?? project?.id))) {
    return getNotLocalAllocationKey(assignment?.project_id ?? project?.id);
  }

  return classifyAllocationProject(projectName);
}

const RESOURCE_SUMMARY_WEEKS_PER_MONTH = 4;

function getResourceSummaryFiscalWeekCount() {
  return fiscalMonths(S.matrixFiscalYear).length * RESOURCE_SUMMARY_WEEKS_PER_MONTH;
}

function createEmptyAllocationTotals(allocationColumns = getResourceSummaryAllocationColumns()) {
  return Object.fromEntries(
    allocationColumns.map(column => [column.key, 0]),
  );
}

function createEmptyRevenueTotals(revenueColumns = getResourceSummaryRevenueColumns()) {
  return Object.fromEntries(
    revenueColumns.map(column => [column.key, 0]),
  );
}

function getEmployeeFiscalAssignmentTotals(
  employeeId,
  allocationColumns = getResourceSummaryAllocationColumns(),
  revenueColumns = getResourceSummaryRevenueColumns(),
) {
  const percentageTotals = createEmptyAllocationTotals(allocationColumns);
  const hourTotals = createEmptyRevenueTotals(revenueColumns);

  getEffectiveFiscalAssignments(S.matrixFiscalYear, S.matrixAssignments).forEach(assignment => {
    if (Number(assignment.employee_id) !== Number(employeeId)) return;

    const percentage = Number(assignment.percentage);
    if (!Number.isFinite(percentage)) return;

    const categoryKey = classifyResourceSummaryAssignment(assignment);
    if (Object.prototype.hasOwnProperty.call(percentageTotals, categoryKey)) {
      percentageTotals[categoryKey] += percentage;
    }

    // Revenue uses the same visible category key as Allocation. Therefore a
    // Not Local project is removed from the generic Local revenue bucket and
    // receives its own project-specific Revenue column.
    if (Object.prototype.hasOwnProperty.call(hourTotals, categoryKey)) {
      hourTotals[categoryKey] += WORK_HOURS_PER_WEEK * (percentage / 100);
    }
  });

  return { percentageTotals, hourTotals };
}

function getRevenueRateValue(rateRecord, revenueKeyOrColumn) {
  const column = typeof revenueKeyOrColumn === 'object'
    ? revenueKeyOrColumn
    : getResourceSummaryRevenueColumn(revenueKeyOrColumn);
  const rateKey = column?.rateKey || String(revenueKeyOrColumn || '');
  const field = RESOURCE_REVENUE_RATE_FIELDS[rateKey];
  if (!field) return null;

  const value = Number(rateRecord?.[field]);
  return Number.isFinite(value) && value >= 0 ? value : null;
}


const MATRIX_PLANNED_REVENUE_KEYS = new Set(['intrasourcing', 'local']);

function getMatrixAssignmentCardRevenue(employee, assignment, unavailableSlots = null) {
  const categoryKey = classifyAllocationProject(
    getSummaryAssignmentProjectName(assignment),
  );

  if (categoryKey !== 'preSale') {
    return getMatrixAssignmentPlannedRevenue(employee, assignment, unavailableSlots);
  }

  if (unavailableSlots && isEmployeeUnavailableForSlot(
    employee.id,
    Number(assignment.year),
    Number(assignment.month),
    Number(assignment.week),
    unavailableSlots,
  )) {
    return {
      eligible: false,
      categoryKey,
      hours: 0,
      rate: null,
      amount: 0,
      hasRate: true,
      basis: 'preSaleProductAmount',
      productName: '',
    };
  }

  const productName = String(
    assignment.product_name || assignment.assignment_product_name || '',
  ).trim();
  const masterProduct = typeof getPreSaleProductByName === 'function'
    ? getPreSaleProductByName(productName)
    : null;
  const directAmountSource = assignment.presale_product_amount;
  const masterAmountSource = masterProduct?.amount;
  const directAmount = directAmountSource === null || directAmountSource === undefined || directAmountSource === ''
    ? null
    : Number(directAmountSource);
  const masterAmount = masterAmountSource === null || masterAmountSource === undefined || masterAmountSource === ''
    ? null
    : Number(masterAmountSource);
  const amount = Number.isFinite(masterAmount)
    ? masterAmount
    : Number.isFinite(directAmount)
      ? directAmount
      : null;

  return {
    eligible: true,
    categoryKey,
    hours: 0,
    rate: null,
    amount,
    hasRate: amount !== null,
    basis: 'preSaleProductAmount',
    productName: masterProduct?.name || productName,
  };
}

function getMatrixAssignmentPlannedRevenue(employee, assignment, unavailableSlots = null) {
  const categoryKey = classifyAllocationProject(
    getSummaryAssignmentProjectName(assignment),
  );

  if (!MATRIX_PLANNED_REVENUE_KEYS.has(categoryKey)) {
    return { eligible: false, categoryKey, hours: 0, rate: 0, amount: 0, hasRate: true };
  }

  if (unavailableSlots && isEmployeeUnavailableForSlot(
    employee.id,
    Number(assignment.year),
    Number(assignment.month),
    Number(assignment.week),
    unavailableSlots,
  )) {
    return { eligible: false, categoryKey, hours: 0, rate: 0, amount: 0, hasRate: true };
  }

  const percentage = Number(assignment.percentage);
  const hours = Number.isFinite(percentage) && percentage > 0
    ? WORK_HOURS_PER_WEEK * (percentage / 100)
    : 0;
  const rateRecord = getRevenueRateForDesignation(employee.designation);
  const rate = getRevenueRateValue(rateRecord, categoryKey);

  return {
    eligible: true,
    categoryKey,
    hours,
    rate,
    amount: rate === null ? null : hours * rate,
    hasRate: rate !== null,
  };
}

function getMatrixAssignmentSummaryRevenue(employee, assignment, unavailableSlots = null) {
  const categoryKey = classifyResourceSummaryAssignment(assignment);
  const revenueColumn = getResourceSummaryRevenueColumn(categoryKey);

  if (!revenueColumn) {
    return { eligible: false, categoryKey, hours: 0, rate: 0, amount: 0, hasRate: true };
  }

  if (unavailableSlots && isEmployeeUnavailableForSlot(
    employee.id,
    Number(assignment.year),
    Number(assignment.month),
    Number(assignment.week),
    unavailableSlots,
  )) {
    return { eligible: false, categoryKey, hours: 0, rate: 0, amount: 0, hasRate: true };
  }

  const percentage = Number(assignment.percentage);
  const hours = Number.isFinite(percentage) && percentage > 0
    ? WORK_HOURS_PER_WEEK * (percentage / 100)
    : 0;
  const rateRecord = getRevenueRateForDesignation(employee.designation);
  const rate = getRevenueRateValue(rateRecord, revenueColumn);

  return {
    eligible: true,
    categoryKey,
    rateKey: revenueColumn.rateKey,
    hours,
    rate,
    amount: rate === null ? null : hours * rate,
    hasRate: rate !== null,
  };
}

function getMatrixWeekPlannedRevenue(employeeRows, month, week, unavailableSlots = null) {
  let amount = 0;
  let unpricedHours = 0;
  const revenueColumns = getResourceSummaryRevenueColumns();
  const byCategory = Object.fromEntries(revenueColumns.map(column => [column.key, 0]));

  for (const employee of employeeRows || []) {
    const key = `${month.y}-${month.m}-${week}`;
    const assignments = S.matrix[employee.id]?.[key] || [];

    for (const assignment of assignments) {
      const revenue = getMatrixAssignmentSummaryRevenue(
        employee,
        assignment,
        unavailableSlots,
      );
      if (!revenue.eligible) continue;
      if (!revenue.hasRate) {
        unpricedHours += revenue.hours;
        continue;
      }

      amount += revenue.amount;
      if (Object.prototype.hasOwnProperty.call(byCategory, revenue.categoryKey)) {
        byCategory[revenue.categoryKey] += revenue.amount;
      }
    }
  }

  return { amount, unpricedHours, byCategory, revenueColumns };
}

function getMatrixMonthPlannedRevenue(employeeRows, month, unavailableSlots = null) {
  let amount = 0;
  let unpricedHours = 0;
  const revenueColumns = getResourceSummaryRevenueColumns();
  const byCategory = Object.fromEntries(revenueColumns.map(column => [column.key, 0]));

  for (let week = 1; week <= RESOURCE_SUMMARY_WEEKS_PER_MONTH; week += 1) {
    const weeklyRevenue = getMatrixWeekPlannedRevenue(
      employeeRows,
      month,
      week,
      unavailableSlots,
    );
    amount += weeklyRevenue.amount;
    unpricedHours += weeklyRevenue.unpricedHours;
    revenueColumns.forEach(column => {
      byCategory[column.key] += Number(weeklyRevenue.byCategory?.[column.key]) || 0;
    });
  }

  return { amount, unpricedHours, byCategory, revenueColumns };
}

function getResourceSummaryViewData(employee) {
  const allocationColumns = getResourceSummaryAllocationColumns();
  const revenueColumns = getResourceSummaryRevenueColumns();
  const fiscalWeekCount = getEmployeeAvailableFiscalWeekCount(
    employee.id,
    S.matrixFiscalYear,
    S.matrixAssignments,
  );
  const { percentageTotals, hourTotals } = getEmployeeFiscalAssignmentTotals(
    employee.id,
    allocationColumns,
    revenueColumns,
  );

  const allocation = Object.fromEntries(
    allocationColumns.map(column => [
      column.key,
      fiscalWeekCount ? percentageTotals[column.key] / fiscalWeekCount : 0,
    ]),
  );

  const rateRecord = getRevenueRateForDesignation(employee.designation);
  const revenue = createEmptyRevenueTotals(revenueColumns);
  const revenueMeta = {
    designation: employee.designation || '',
    hasRevenueRateRecord: Boolean(rateRecord),
  };

  revenueColumns.forEach(column => {
    const hours = Number(hourTotals[column.key]) || 0;
    const rate = getRevenueRateValue(rateRecord, column);
    const amount = rate === null ? null : hours * rate;

    revenue[column.key] = amount;
    revenueMeta[column.key] = {
      hours,
      rate,
      revenue: amount,
      rateField: RESOURCE_REVENUE_RATE_FIELDS[column.rateKey],
      rateKey: column.rateKey,
      hasRevenueRate: rate !== null,
    };
  });

  const notLocalProjects = allocationColumns
    .filter(column => column.isNotLocalProject && Number(percentageTotals[column.key]) > 0)
    .map(column => ({
      id: column.projectId,
      code: column.projectCode,
      name: column.label,
      allocation: Number(allocation[column.key]) || 0,
      revenue: revenue[column.key],
    }));

  return {
    allocationColumns,
    revenueColumns,
    allocation,
    allocationMeta: {
      percentageTotals,
      fiscalWeekCount,
      total: Object.values(allocation).reduce((sum, value) => sum + value, 0),
      notLocalProjects,
    },
    revenue,
    revenueMeta,
  };
}

